#!/usr/bin/env bash
# Decentralized secrets provisioning (Lab 10).
#
# Decentralized approach: EACH environment/developer/team generates and keeps
# its own secret file - there is no central store. The generated .env is the
# "external storage" consumed by the app (app/config.py, source=file).
# Rotation = re-run this script (or per-secret env override at start).
#
# Usage:
#   ./scripts/provision_decentralized.sh            # create .env (fails if exists)
#   ./scripts/provision_decentralized.sh --force    # rotate all secrets
set -euo pipefail

cd "$(dirname "$0")/.."
ENV_FILE=".env"

secret() { openssl rand -hex "${1:-32}"; }

if [[ -f "$ENV_FILE" && "${1:-}" != "--force" ]]; then
  echo "[!] $ENV_FILE already exists (this environment is already provisioned)."
  echo "    Use '$0 --force' to rotate every secret."
  exit 1
fi

umask 077  # resulting file gets 600

DB_PASSWORD="$(secret 24)"
cat > "$ENV_FILE" <<EOF
# Decentralized secrets file (external storage: FILE). chmod 600, git-ignored.
# Generated by scripts/provision_decentralized.sh on $(date -u +%FT%TZ)
APP_SECRETS_SOURCE=file
APP_SECRET_KEY=$(secret 32)
JWT_SECRET=$(secret 32)
DATABASE_URL=postgresql://app_user:${DB_PASSWORD}@db.internal:5432/appdb
EXTERNAL_API_TOKEN=$(secret 24)
SMTP_HOST=smtp.example.org
SMTP_USER=service@example.org
SMTP_PASSWORD=$(secret 24)
EOF
chmod 600 "$ENV_FILE"

echo "[+] $ENV_FILE written (0600) with freshly generated secrets."
echo "    Run the app with this file:     make run"
echo "    Or inject as process env:       set -a; . ./$ENV_FILE; set +a; APP_SECRETS_SOURCE=env python3 -m app.main"
echo "    Values are NOT printed here and MUST NOT be committed."
